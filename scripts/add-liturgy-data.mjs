function splitIntoColons(text) {
  const lines = text.split(/\s*\/+\s*/).map(s => s.trim()).filter(Boolean);
  return { colonText: lines.join(' / '), lines };
}

function makeHymn({ id, type, category, glas, rawText, rank = 'ordinary' }) {
  const { colonText, lines } = splitIntoColons(rawText);
  return { id, type, rank, category, glas: glas || null, colonText, lines };
}

