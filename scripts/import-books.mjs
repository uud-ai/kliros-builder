async function generateMineyaForDownloadedDates() {
  const minBaseDir = path.join(OUT_DIR, 'mineya');
  await fs.mkdir(minBaseDir, { recursive: true });

  const buDir = path.resolve('public/data/bu');
  let buFiles = [];
  try {
    buFiles = (await fs.readdir(buDir)).filter(f => /^\d{4}-\d{2}-\d{2}\.json$/.test(f));
  } catch {}

  let count = 0;
  for (const f of buFiles) {
    const bu = JSON.parse(await fs.readFile(path.join(buDir, f), 'utf-8'));
    const oldStyle = bu.oldStyleDate || f.slice(0, 10);
    const mm = oldStyle.slice(5, 7);
    const mmdd = oldStyle.slice(5, 10);

    const monthDir = path.join(minBaseDir, mm);
    await fs.mkdir(monthDir, { recursive: true });

    const fullHeader = bu.variants?.[0]?.header || bu.variants?.[0]?.title || `Минея ${mmdd}`;
    const isHierarch = /свт\.|святител|патриарх|архиеп/i.test(fullHeader);
    const isMonastic = /прп\.|преподоб/i.test(fullHeader);
    const tpl = isHierarch ? COMMON_MINEYA_TEMPLATES.hierarchs : isMonastic ? COMMON_MINEYA_TEMPLATES.monastics : COMMON_MINEYA_TEMPLATES.martyrs;

    const mineyaDayObj = {
      date: mmdd,
      title: fullHeader,
      vespers: {
        stichera_saints: tpl.stichera.map((raw, idx) =>
          buildHymnItem({
            id: `min_${mmdd}_gv_${idx + 1}`,
            type: 'stichera',
            category: `Стихиры святого Минеи (${mmdd} ст. ст.)`,
            glas: tpl.glas,
            rawText: raw
          })
        ),
        stichovna_glory: buildHymnItem({
          id: `min_${mmdd}_stichovna_glory`,
          type: 'stichera',
          rank: 'glory',
          category: `Славник святого на стиховне (${mmdd} ст. ст.)`,
          glas: tpl.glas,
          rawText: tpl.stichovna_glory
        })
      },
      troparion: buildHymnItem({
        id: `min_${mmdd}_trop`,
        type: 'troparion',
        rank: 'saint',
        category: `Тропарь святого Минеи (${mmdd} ст. ст.)`,
        glas: tpl.glas,
        rawText: tpl.troparion
      }),
      matins: {
        sedalny: [
          buildHymnItem({
            id: `min_${mmdd}_sed`,
            type: 'sedalen',
            category: `Седален святого по 3-й песни (${mmdd} ст. ст.)`,
            glas: tpl.glas,
            rawText: tpl.sedalen
          })
        ],
        lauds_stichera: tpl.stichera.map((raw, idx) =>
          buildHymnItem({
            id: `min_${mmdd}_lauds_${idx + 1}`,
            type: 'stichera',
            category: `Стихира святого на хвалитех (${mmdd} ст. ст.)`,
            glas: tpl.glas,
            rawText: raw
          })
        ),
        lauds_glory: buildHymnItem({
          id: `min_${mmdd}_lauds_glory`,
          type: 'stichera',
          rank: 'glory',
          category: `Славник на хвалитех (${mmdd} ст. ст.)`,
          glas: tpl.glas,
          rawText: tpl.stichovna_glory
        })
      }
    };

    await fs.writeFile(path.join(monthDir, `${mmdd}.json`), JSON.stringify(mineyaDayObj, null, 2), 'utf-8');
    count++;
  }
  console.log(`[OK] Минея: обновлено ${count} ежедневных файлов со стихирами и славниками на хвалитех.`);
}

